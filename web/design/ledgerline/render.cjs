// Renders the Ledgerline mock screens to WebP and writes the scanner's highlight boxes.
// Dev-only, not part of the site build. From web/:
//   npm i --no-save playwright-core   (once; uses the installed Google Chrome)
//   node design/ledgerline/render.cjs
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("playwright-core");

const W = 1200, H = 760, SCALE = 2, QUALITY = 0.82;
const here = __dirname;
const web = path.resolve(here, "../..");
const out = path.join(web, "public/ledgerline");

(async () => {
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ channel: "chrome" });
  const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: SCALE });
  let targets = [];

  for (const name of ["before", "after"]) {
    await page.goto("file://" + path.join(here, `${name}.html`));
    await page.evaluate(() => document.fonts.ready);
    const png = await page.screenshot({ type: "png", omitBackground: false });
    if (name === "before") {
      targets = await page.$$eval("[data-scan]", (els, [w, h]) => els.map((el) => {
        const r = el.getBoundingClientRect();
        const pct = (v, d) => +((v / d) * 100).toFixed(2);
        return { tag: el.dataset.tag, x: pct(r.left, w), y: pct(r.top, h), w: pct(r.width, w), h: pct(r.height, h) };
      }), [W, H]);
    }
    // Encode with the browser's own WebP encoder: no image tooling needed.
    const webp = await page.evaluate(async ({ b64, q }) => {
      const img = new Image();
      img.src = "data:image/png;base64," + b64;
      await img.decode();
      const c = document.createElement("canvas");
      c.width = img.naturalWidth; c.height = img.naturalHeight;
      c.getContext("2d").drawImage(img, 0, 0);
      return c.toDataURL("image/webp", q).split(",")[1];
    }, { b64: png.toString("base64"), q: QUALITY });
    const file = path.join(out, `${name}.webp`);
    fs.writeFileSync(file, Buffer.from(webp, "base64"));
    console.log(`${path.relative(web, file)}  ${(fs.statSync(file).size / 1024).toFixed(0)} KB`);
  }

  const ts = `// Generated by design/ledgerline/render.cjs. Boxes are % of the ${W}x${H} before.webp frame.\n` +
    `export const LEDGERLINE_SIZE = { width: ${W}, height: ${H} } as const;\n` +
    `export const SCAN_TARGETS = ${JSON.stringify(targets, null, 2)} as const;\n`;
  fs.writeFileSync(path.join(web, "components/landing/ledgerline-targets.ts"), ts);
  await browser.close();
})();
